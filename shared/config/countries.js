/**
 * Coerce a free-text or code-like country value into an ISO 3166-1 alpha-2
 * code, or '' if it can't be confidently mapped.
 *
 *   normalizeCountryToIso2('US')             → 'US'
 *   normalizeCountryToIso2('us')             → 'US'
 *   normalizeCountryToIso2('United States')  → 'US'
 *   normalizeCountryToIso2('USA')            → 'US'
 *   normalizeCountryToIso2('Freedonia')      → ''   (unknown — caller defaults)
 *   normalizeCountryToIso2(undefined)        → ''
 *
 * @param {*} input
 * @returns {string} uppercase ISO2 code, or '' when unmappable
 */
export function normalizeCountryToIso2(input) {
  if (typeof input !== 'string') return '';
  const trimmed = input.trim();
  if (!trimmed) return '';

  // Already a valid 2-char code (any case).
  if (trimmed.length === 2 && CODE_SET.has(trimmed.toUpperCase())) {
    return trimmed.toUpperCase();
  }

  const lower = trimmed.toLowerCase();
  if (NAME_TO_CODE.has(lower)) return NAME_TO_CODE.get(lower);
  if (ALIASES.has(lower)) return ALIASES.get(lower);

  return '';
}

/** True if `code` is a recognized ISO2 country code (case-insensitive). */
export function isIso2Country(code) {
  return typeof code === 'string' && CODE_SET.has(code.toUpperCase());
}
